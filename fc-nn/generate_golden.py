"""Generate actor arithmetic references from the actual firmware header (no Torch)."""
from pathlib import Path
import hashlib
from fw_common import parse_weights_h, nn_forward_np
from test_nn_parity import golden_observations


def main():
    root = Path(__file__).resolve().parent.parent
    header = root / "weights.h"
    weights = parse_weights_h(header)
    rows = golden_observations()
    lines = ["/* Generated by generate_golden.py; do not edit. */",
             f'/* weights.h SHA256: {hashlib.sha256(header.read_bytes()).hexdigest()} */',
             f"#define N_GOLDEN {len(rows)}",
             "static const char *golden_names[N_GOLDEN] = {"]
    lines += [f'    "{name}",' for name, _ in rows]
    lines += ["};"]
    for name, vectors, width in [
        ("golden_obs", [obs for _, obs in rows], 12),
        ("golden_out", [nn_forward_np(weights, obs) for _, obs in rows], 4),
    ]:
        lines += [f"static const float {name}[N_GOLDEN][{width}] = {{"]
        lines += ["    {" + ", ".join(f"{v:.9e}f" for v in row) + "}," for row in vectors]
        lines += ["};"]
    (root / "host_test" / "golden_vectors.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
