"""
export_weights.py  –  Extract weights from a trained SB3 PPO model and write
                      them to weights.h for the STM32 firmware.

Array names match the C firmware exactly:
    W1[32][12]  B1[32]      (input  -> hidden-1, ReLU)
    W2[32][32]  B2[32]      (hidden-1 -> hidden-2, ReLU)
    W3[4][32]   B3[4]       (hidden-2 -> output, linear)

Usage:
    python export_weights.py runs/quad_hover/best_model.zip
    python export_weights.py runs/quad_hover/best_model.zip --out weights.h
"""

import argparse
import datetime
import numpy as np
from stable_baselines3 import PPO


def extract_weights(model_path: str):
    """
    Load an SB3 PPO model and return the six weight/bias arrays.

    Returns
    -------
    W1 : ndarray (32, 12)
    B1 : ndarray (32,)
    W2 : ndarray (32, 32)
    B2 : ndarray (32,)
    W3 : ndarray (4,  32)
    B3 : ndarray (4,)
    """
    model = PPO.load(model_path)

    # SB3 MlpPolicy actor layers are stored in
    #   model.policy.mlp_extractor.policy_net   (shared MLP)
    #   model.policy.action_net                  (final output layer)
    #
    # net_arch=[32, 32] produces:
    #   policy_net[0]: Linear(12 -> 32)   (+ ReLU activation – not a layer)
    #   policy_net[2]: Linear(32 -> 32)
    #   action_net   : Linear(32 -> 4)
    #
    # The activation modules sit at indices 1, 3 in the Sequential, so the
    # Linear modules are at 0 and 2.

    policy_net = model.policy.mlp_extractor.policy_net

    # Locate Linear layers in the sequential (skip activation modules)
    linear_layers = [m for m in policy_net if hasattr(m, "weight")]

    if len(linear_layers) != 2:
        raise RuntimeError(
            f"Expected 2 Linear layers in policy_net, found {len(linear_layers)}. "
            "Make sure the model was trained with net_arch=[32, 32]."
        )

    layer1, layer2 = linear_layers
    layer3 = model.policy.action_net

    W1 = layer1.weight.detach().cpu().numpy().astype(np.float32)  # (32, 12)
    B1 = layer1.bias.detach().cpu().numpy().astype(np.float32)    # (32,)
    W2 = layer2.weight.detach().cpu().numpy().astype(np.float32)  # (32, 32)
    B2 = layer2.bias.detach().cpu().numpy().astype(np.float32)    # (32,)
    W3 = layer3.weight.detach().cpu().numpy().astype(np.float32)  # (4,  32)
    B3 = layer3.bias.detach().cpu().numpy().astype(np.float32)    # (4,)

    # Sanity checks
    assert W1.shape == (32, 12), f"W1 shape mismatch: {W1.shape}"
    assert B1.shape == (32,),    f"B1 shape mismatch: {B1.shape}"
    assert W2.shape == (32, 32), f"W2 shape mismatch: {W2.shape}"
    assert B2.shape == (32,),    f"B2 shape mismatch: {B2.shape}"
    assert W3.shape == (4,  32), f"W3 shape mismatch: {W3.shape}"
    assert B3.shape == (4,),     f"B3 shape mismatch: {B3.shape}"

    return W1, B1, W2, B2, W3, B3


def array_to_c(name: str, arr: np.ndarray) -> str:
    """Format a numpy array as a C float array literal."""
    arr = arr.astype(np.float32)
    flat = arr.flatten()

    # Build dimension suffix, e.g. [32][10] or [32]
    dims = "".join(f"[{d}]" for d in arr.shape)

    lines = [f"const float {name}{dims} = {{"]
    ROW_WIDTH = 8   # values per line (cosmetic)
    for i in range(0, len(flat), ROW_WIDTH):
        chunk = flat[i : i + ROW_WIDTH]
        vals  = ", ".join(f"{v:.9e}f" for v in chunk)
        lines.append(f"    {vals},")
    lines.append("};")
    return "\n".join(lines)


def write_header(W1, B1, W2, B2, W3, B3, out_path: str):
    timestamp = datetime.datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")

    guard = "WEIGHTS_H"
    sections = [
        f"/* Auto-generated by export_weights.py on {timestamp} */",
        f"/* Network: 12 -> 32 (ReLU) -> 32 (ReLU) -> 4 (linear)       */",
        f"/* All weights are float32 (IEEE 754 single precision)         */",
        f"/*                                                              */",
        f"/* Action mapping (residual):                                   */",
        f"/*   motor_cmd = clip(HOVER_THR + nn_output * ACT_SCALE, 0, 1) */",
        f"/*   motor_pwm_us = motor_cmd * 1000.0f + 1000.0f              */",
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "/* Residual action mapping constants */",
        "#define NN_HOVER_THROTTLE  0.3226f",
        "#define NN_ACTION_SCALE    0.4f",
        "",
        array_to_c("W1", W1), "",
        array_to_c("B1", B1), "",
        array_to_c("W2", W2), "",
        array_to_c("B2", B2), "",
        array_to_c("W3", W3), "",
        array_to_c("B3", B3), "",
        f"#endif /* {guard} */",
        "",
    ]

    with open(out_path, "w") as f:
        f.write("\n".join(sections))

    print(f"[export] Written to {out_path}")
    print(f"         W1{list(W1.shape)}, B1{list(B1.shape)}")
    print(f"         W2{list(W2.shape)}, B2{list(B2.shape)}")
    print(f"         W3{list(W3.shape)}, B3{list(B3.shape)}")


def main():
    parser = argparse.ArgumentParser(
        description="Export SB3 PPO weights to a C header file."
    )
    parser.add_argument("model", help="Path to the .zip model file (or without extension).")
    parser.add_argument("--out", default="weights.h",
                        help="Output header file path (default: weights.h).")
    args = parser.parse_args()

    W1, B1, W2, B2, W3, B3 = extract_weights(args.model)
    write_header(W1, B1, W2, B2, W3, B3, args.out)


if __name__ == "__main__":
    main()
